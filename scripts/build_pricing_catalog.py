#!/usr/bin/env python3
"""Write web/src/lib/pricing/catalog.ts from the pricing workbook.

Films, pricing-group rates, and the bulk-discount table are copied from
data/ScottishPricing-26_12-Accounts.xlsm. Nothing here is typed by hand.
"""

from __future__ import annotations

import json
from pathlib import Path

import openpyxl

ROOT = Path(__file__).resolve().parents[1]
WORKBOOK = ROOT / "data" / "ScottishPricing-26_12-Accounts.xlsm"
OUT = ROOT / "web" / "src" / "lib" / "pricing" / "catalog.ts"

# Dropdown lists on Film Pricing. A film's brand is the list that contains it.
BRAND_RANGES = (
    (74, 94, "Vista"),
    (97, 205, "Llumar"),
    (209, 348, "3M"),
    (351, 378, "Huper"),
    (382, 392, "Other"),
)
SECTION_HEADERS = {"VISTA", "3M WINDOW FILM", "HUPER OPTIK", "Other", "Llumar"}


def brand_for(row: int) -> str | None:
    for start, end, brand in BRAND_RANGES:
        if start <= row <= end:
            return brand
    return None


def ts_num(value: float | int) -> str:
    if isinstance(value, bool):
        raise TypeError(value)
    if isinstance(value, int):
        return str(value)
    # .12g turns binary artifacts such as 8.210999999999999 back into 8.211.
    return format(float(value), ".12g")


def main() -> None:
    formulas = openpyxl.load_workbook(WORKBOOK, data_only=False)
    cached = openpyxl.load_workbook(WORKBOOK, data_only=True)
    sheet = formulas["Preferences"]
    values = cached["Preferences"]

    rates: dict[int, float] = {}
    for row in range(47, 57):
        group = sheet.cell(row, 4).value
        price = sheet.cell(row, 6).value
        if isinstance(group, int) and isinstance(price, (int, float)):
            rates[group] = float(price)

    thresholds: list[float] = []
    for col in range(6, 19):  # F34:R34
        cell = sheet.cell(34, col).value
        if isinstance(cell, (int, float)):
            thresholds.append(float(cell))
    if thresholds != [0, 500, 1000, 1500, 2000, 2500, 3000, 4000, 5000, 7500, 10000, 20000, 50000]:
        raise SystemExit(f"unexpected discount thresholds: {thresholds}")

    rate_rows: list[tuple[int, list[float | None]]] = []
    for row in range(35, 45):
        group = sheet.cell(row, 5).value
        if not isinstance(group, int):
            raise SystemExit(f"discount row {row} has no group")
        cells: list[float | None] = []
        for col in range(6, 19):
            cell = sheet.cell(row, col).value
            if cell is None or cell == "":
                cells.append(None)
            elif isinstance(cell, (int, float)):
                cells.append(float(cell))
            else:
                raise SystemExit(f"unexpected discount cell {sheet.cell(row, col).coordinate}={cell!r}")
        rate_rows.append((group, cells))

    films: list[dict[str, object]] = []
    flagged: list[str] = []
    for row in range(74, 393):
        name = sheet.cell(row, 1).value
        if not isinstance(name, str) or not name.strip():
            continue
        if name.strip() in SECTION_HEADERS and sheet.cell(row, 4).value is None:
            continue
        brand = brand_for(row)
        if brand is None:
            flagged.append(f"row {row} {name!r} is outside every manufacturer list")
            continue
        cost = sheet.cell(row, 3).value
        group_cell = sheet.cell(row, 4).value
        cached_group = values.cell(row, 4).value
        if isinstance(group_cell, str) and group_cell.startswith("="):
            source = "formula"
            group = cached_group if isinstance(cached_group, (int, float)) else None
        elif isinstance(group_cell, (int, float)):
            source = "typed"
            group = group_cell
        else:
            source = "blank"
            group = None
        if group is None and not isinstance(cost, (int, float)):
            continue
        if group is None:
            flagged.append(f"row {row} {name!r} has cost {cost} and no pricing group, so it is omitted")
            continue
        film = {
            "name": name,
            "psf": float(cost) if isinstance(cost, (int, float)) else None,
            "pg": int(group),
            "brand": brand,
            "groupSource": source,
        }
        if any(existing == film for existing in films):
            flagged.append(f"row {row} {name!r} is an exact duplicate of an earlier row, so it is listed once")
            continue
        films.append(film)

    version = sheet["A2"].value
    dated = sheet["A3"].value
    min_dim = sheet["E10"].value
    min_price = sheet["E11"].value
    removal = formulas["Film Pricing"]["K43"].value
    french = formulas["Film Pricing"]["K44"].value
    cbond = values["J29"].value

    lines: list[str] = []
    lines.append("// Generated by scripts/build_pricing_catalog.py from")
    lines.append("// data/ScottishPricing-26_12-Accounts.xlsm. Do not edit by hand.")
    lines.append("// Re-run the script after the workbook changes.")
    lines.append("")
    lines.append("export interface CatalogFilm {")
    lines.append("  name: string;")
    lines.append("  /** Film cost per square foot (Preferences column C). Null for a typed group with no cost. */")
    lines.append("  psf: number | null;")
    lines.append("  /** Pricing group. Formula cells use the value Excel stored; typed cells use the number in the cell. */")
    lines.append("  pg: number;")
    lines.append("  brand: string;")
    lines.append("  /** formula = VLOOKUP of the cost. typed = a number written over the formula. */")
    lines.append('  groupSource: "formula" | "typed";')
    lines.append("}")
    lines.append("")
    lines.append(f"export const WORKBOOK_VERSION = {json.dumps(str(version))};")
    lines.append(f"export const WORKBOOK_DATED = {json.dumps(str(dated)[:10])};")
    lines.append("/** Preferences!E10. Film Pricing formulas do not reference it. */")
    lines.append(f"export const WORKBOOK_MIN_DIMENSION_INCHES = {ts_num(min_dim)};")
    lines.append("/** Preferences!E11, labeled Minimum Window Price. Film Pricing formulas do not reference it. */")
    lines.append(f"export const WORKBOOK_MIN_WINDOW_PRICE = {ts_num(min_price)};")
    lines.append("/** Film Pricing!K50 multiplies the subtotal by this. */")
    lines.append("export const WORKBOOK_FEE_RATE = 0.04;")
    lines.append("/** Literal in Film Pricing!K43. */")
    lines.append("export const WORKBOOK_REMOVAL_PER_SQ_FT = 1.25;")
    lines.append("/** Literal in Film Pricing!K44. */")
    lines.append("export const WORKBOOK_FRENCH_PANE_EACH = 3;")
    lines.append("/** Preferences!J29, used by Film Pricing!K48 when C-Bond is checked. */")
    lines.append(f"export const WORKBOOK_CBOND_PER_CHARGED_SQ_FT = {ts_num(cbond)};")
    lines.append("")
    lines.append("/** Price_Group column F (Preferences!F47:F56). Customer dollars per charged square foot. */")
    lines.append("export const PRICING_GROUP_RATES: Record<number, number> = {")
    for group in range(1, 11):
        lines.append(f"  {group}: {ts_num(rates[group])},")
    lines.append("};")
    lines.append("")
    lines.append("/** Preferences!F34:R34. */")
    lines.append("export const BULK_DISCOUNT_THRESHOLDS = [")
    lines.append("  " + ", ".join(ts_num(v) for v in thresholds) + ",")
    lines.append("] as const;")
    lines.append("")
    lines.append("/**")
    lines.append(" * Preferences!F35:R44. null is an empty cell. HLOOKUP of an empty cell returns 0.")
    lines.append(" * Row index in Film Pricing!K47 is the pricing group plus one (the header is row 1).")
    lines.append(" */")
    lines.append("export const BULK_DISCOUNT_RATES: Record<number, readonly (number | null)[]> = {")
    for group, cells in rate_rows:
        rendered = ", ".join("null" if cell is None else ts_num(cell) for cell in cells)
        lines.append(f"  {group}: [{rendered}],")
    lines.append("};")
    lines.append("")
    lines.append("export const FILMS: CatalogFilm[] = [")
    for film in films:
        psf = "null" if film["psf"] is None else ts_num(film["psf"])  # type: ignore[arg-type]
        lines.append(
            "  { "
            f"name: {json.dumps(film['name'])}, "
            f"psf: {psf}, "
            f"pg: {film['pg']}, "
            f"brand: {json.dumps(film['brand'])}, "
            f"groupSource: {json.dumps(film['groupSource'])} "
            "},"
        )
    lines.append("];")
    lines.append("")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT} films={len(films)} groups={len(rates)}")
    print("flagged:")
    for line in flagged:
        print(" ", line)
    print("removal formula", removal)
    print("french formula", french)


if __name__ == "__main__":
    main()
